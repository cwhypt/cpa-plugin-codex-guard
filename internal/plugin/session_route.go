package plugin

import (
	"encoding/json"
	"net/http"
	"strings"
	"time"

	"cpa-codex-guard/internal/sessionroute"
	"cpa-codex-guard/internal/types"
)

const internalRouteHeader = "X-Cpa-Internal-Session-Route"

func hasInternalRouteHeader(headers http.Header) bool {
	for name := range headers {
		if strings.EqualFold(name, internalRouteHeader) {
			return true
		}
	}
	return false
}

type sessionRouter struct {
	config *sessionroute.Config
	store  *sessionroute.Store
}

func routeCaller(req *types.RequestInterceptRequest) string {
	if caller := strings.TrimSpace(req.CallerScope); caller != "" {
		return caller
	}
	return stringValue(req.Metadata, "caller_scope")
}

// Cache hits may keep an existing session alive, but never classify or bind one.
func (e *Engine) refreshCachedSessionRoute(req *types.RequestInterceptRequest, body []byte) {
	e.mu.RLock()
	router := e.sessionRouter
	e.mu.RUnlock()
	caller := routeCaller(req)
	if router == nil || caller == "" || !router.config.IncludesModel(req.Model) {
		return
	}
	session := sessionroute.SessionID(req.GetHeaders(), body, req.Metadata)
	if session == "" {
		return
	}
	key, err := sessionroute.Key(caller, session)
	if err == nil {
		err = router.store.TouchExistingKey(key)
	}
	if err != nil {
		e.debugLog("session-route", "cached session TTL refresh failed")
	}
}

// This runs only after local computation and cache lookup have missed.
func (e *Engine) prepareSessionRoute(req *types.RequestInterceptRequest, body []byte) (http.Header, []string) {
	var clear []string
	if hasInternalRouteHeader(req.GetHeaders()) {
		clear = []string{internalRouteHeader}
	}
	e.mu.RLock()
	router := e.sessionRouter
	e.mu.RUnlock()
	caller := routeCaller(req)
	if router == nil || !router.config.IncludesModel(req.Model) || caller == "" || req.RequestID == "" {
		return nil, clear
	}
	session := sessionroute.SessionID(req.GetHeaders(), body, req.Metadata)
	if session == "" {
		// No explicit session: isolate the request rather than merging prompt matches.
		session = "request:" + req.RequestID
	}
	key, err := sessionroute.Key(caller, session)
	if err != nil {
		return nil, clear
	}
	binding, exists, err := router.store.LookupKey(key)
	if err != nil {
		e.debugLog("session-route", "state lookup failed; using host scheduler")
		return nil, clear
	}
	category := binding.Category
	if !exists {
		var ok bool
		category, ok = router.config.Classify(req.Model, req.GetHeaders().Get("User-Agent"), body)
		if !ok {
			return nil, clear
		}
	}
	binding, err = router.store.ClassifyOnce(caller, session, category)
	if err != nil {
		e.debugLog("session-route", "state write failed; using host scheduler")
		return nil, clear
	}
	e.pendingMu.Lock()
	p := e.pending[req.RequestID]
	if p == nil {
		p = &pendingInfo{}
		e.pending[req.RequestID] = p
	}
	p.routeKey, p.routeExpected, p.routeCaller, p.seenAt = key, binding.AuthID, caller, time.Now()
	e.pendingMu.Unlock()
	// RequestID is generated by the host. The scheduler also checks the trusted
	// caller scope and the live pending record; client header copies are replaced.
	return http.Header{internalRouteHeader: []string{req.RequestID}}, []string{internalRouteHeader}
}

func stringValue(meta map[string]any, key string) string {
	value, _ := meta[key].(string)
	return strings.TrimSpace(value)
}

func (e *Engine) handleSessionRoutePick(raw []byte) ([]byte, error) {
	var req types.SchedulerPickRequest
	if err := json.Unmarshal(raw, &req); err != nil {
		return e.configError(err)
	}
	e.mu.RLock()
	router := e.sessionRouter
	e.mu.RUnlock()
	if router == nil {
		return e.schedulerResult("", false)
	}
	requestID := req.Options.Headers.Get(internalRouteHeader)
	caller := stringValue(req.Options.Metadata, "caller_scope")
	e.pendingMu.Lock()
	p := e.pending[requestID]
	key := ""
	if p != nil && caller != "" && p.routeCaller == caller {
		key = p.routeKey
	}
	e.pendingMu.Unlock()
	if key == "" {
		return e.schedulerResult("", false)
	}
	// Host candidates have already passed model, cooldown and tried-account
	// filtering. Do not infer credential kind from source attributes: OAuth and
	// OpenAI-compatible credentials can both be legitimate configured targets.
	candidates := make([]sessionroute.Candidate, 0, len(req.Candidates))
	for _, candidate := range req.Candidates {
		if candidate.Status == "disabled" {
			continue
		}
		candidates = append(candidates, sessionroute.Candidate{ID: candidate.ID, Priority: candidate.Priority})
	}
	id, handled, err := router.store.PickKey(key, router.config.Categories, candidates)
	if err != nil {
		e.debugLog("session-route", "account reservation failed; using host scheduler")
		return e.schedulerResult("", false)
	}
	if handled {
		e.pendingMu.Lock()
		if current := e.pending[requestID]; current != nil && current.routeKey == key {
			current.routeExpected = id
		}
		e.pendingMu.Unlock()
	}
	return e.schedulerResult(id, handled)
}

func (e *Engine) schedulerResult(id string, handled bool) ([]byte, error) {
	result, err := json.Marshal(types.SchedulerPickResponse{AuthID: id, Handled: handled})
	if err != nil {
		return nil, err
	}
	return json.Marshal(types.Envelope{OK: true, Result: result})
}

func (e *Engine) finishSessionRouteSelection(requestID string, metadata map[string]any) {
	selected := stringValue(metadata, "selected_auth_id")
	if selected == "" {
		return
	}
	e.mu.RLock()
	router := e.sessionRouter
	e.mu.RUnlock()
	e.pendingMu.Lock()
	p := e.pending[requestID]
	key, expected := "", ""
	if p != nil {
		key, expected = p.routeKey, p.routeExpected
	}
	e.pendingMu.Unlock()
	if router == nil || key == "" {
		return
	}
	if err := router.store.RecordFallbackKey(key, expected, selected); err != nil {
		e.debugLog("session-route", "fallback binding failed; keeping previous binding")
		return
	}
	e.pendingMu.Lock()
	if current := e.pending[requestID]; current != nil && current.routeKey == key {
		current.routeExpected = selected
	}
	e.pendingMu.Unlock()
}
